#!/usr/bin/env python3
"""Render a filtered subset of calls from a transcripts jsonl into markdown.

    python scripts/render_calls.py data/transcripts.jsonl --filter address_rejected \
        --out docs/calls_address_rejected.md
"""
import argparse
import json
import os
import re
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from render_labeled import fmt_event  # noqa: E402


def _events(call):
    ev = call.get("events")
    return [e for e in ev if isinstance(e, dict)] if isinstance(ev, list) else []


def f_address_rejected(call):
    """>=1 resolve_address tool_result ok and no get_outage tool_call at all."""
    ev = _events(call)
    has_ok = any(e.get("type") == "tool_result" and e.get("name") == "resolve_address"
                 and e.get("status") == "ok" for e in ev)
    has_outage = any(e.get("type") == "tool_call" and e.get("name") == "get_outage" for e in ev)
    return has_ok and not has_outage


FILTERS = {
    "address_rejected": (f_address_rejected,
                         "Calls A2: address found by the resolver but rejected by the caller"),
}


def attempts(call):
    """For each resolve_address ok result: (args.text, bot readback, caller event or None)."""
    ev = _events(call)
    rows = []
    last_args = {}
    for i, e in enumerate(ev):
        if e.get("type") == "tool_call" and e.get("name") == "resolve_address":
            last_args = e.get("args") if isinstance(e.get("args"), dict) else {}
        if e.get("type") == "tool_result" and e.get("name") == "resolve_address" \
                and e.get("status") == "ok":
            bot = ev[i + 1] if i + 1 < len(ev) and ev[i + 1].get("type") == "bot" else None
            caller = None
            if bot is not None and i + 2 < len(ev) and ev[i + 2].get("type") == "caller":
                caller = ev[i + 2]
            rows.append((last_args.get("text", ""), bot.get("text", "") if bot else "", caller))
    return rows


def town_of(readback):
    m = re.search(r"Overím si:\s*(.*?)\.\s*Je to správne", readback or "", re.S)
    if not m or "," not in m.group(1):
        return None
    return m.group(1).rsplit(",", 1)[1].strip() or None


def esc(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("input")
    ap.add_argument("--filter", required=True, choices=sorted(FILTERS))
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    pred, title = FILTERS[a.filter]

    calls, bad = [], 0
    with open(a.input, encoding="utf-8") as f:
        for ln in f:
            if not ln.strip():
                continue
            try:
                c = json.loads(ln)
                if not isinstance(c, dict):
                    raise ValueError
                if pred(c):
                    calls.append(c)
            except Exception:
                bad += 1
    if bad:
        print(f"skipped {bad} malformed line(s)", file=sys.stderr)

    cmd = f"python scripts/render_calls.py {a.input} --filter {a.filter} --out {a.out}"
    out = [f"# {title}", "", f"Generated by: `{cmd}`", "",
           f"Total matching calls: **{len(calls)}**"
           f" (malformed lines skipped: {bad})", "",
           "Filter (structural): at least one `tool_result` of `resolve_address` with status `ok` "
           "and no `tool_call` of `get_outage`.", ""]

    answers = Counter()
    town_diff = town_same = town_na = 0
    diff_examples = []
    table = []
    for c in calls:
        cid = c.get("call_id")
        for n, (txt, bot, caller) in enumerate(attempts(c), 1):
            ans = caller.get("text", "") if caller else ""
            conf = caller.get("asr_conf") if caller else None
            conf_s = f"{conf:.2f}" if isinstance(conf, (int, float)) else ""
            table.append(f"| {cid} | {n} | {esc(txt)} | {esc(bot)} | {esc(ans) or '—'} | {conf_s} |")
            answers[ans if caller else "(no answer)"] += 1
            town = town_of(bot)
            if town is None or not txt:
                town_na += 1
            elif town.lower() in txt.lower():
                town_same += 1
            else:
                town_diff += 1
                diff_examples.append(cid)

    out += ["## Address: what the caller said vs. what the bot read back", "",
            "| call_id | attempt | what the caller said (args.text) | what the bot read back "
            "| caller's answer | asr_conf |", "|---|---:|---|---|---|---:|"]
    out += table

    for c in calls:
        out += ["", f"### {c.get('call_id')}", "", "```text"]
        out += [fmt_event(e) for e in _events(c)]
        out.append("```")

    calls_with_diff = len(set(diff_examples))
    out += ["", "## Aggregates", "", "Caller's answers to the address confirmation "
            "(per attempt, distinct texts):", "", "| answer | count |", "|---|---:|"]
    out += [f"| {esc(k)} | {v} |" for k, v in sorted(answers.items(), key=lambda x: (-x[1], x[0]))]
    out += ["", "Town check (**heuristic**: the town after the comma in \"Overím si: ..., <town>. "
            "Je to správne?\" is searched as a case-insensitive substring of `args.text`):", "",
            f"- attempts where the town is not in the caller's text: {town_diff}"
            f" (calls: {calls_with_diff})",
            f"- attempts where the town is found in the text: {town_same}",
            f"- could not compare: {town_na}"]

    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(calls)} calls -> {a.out}", file=sys.stderr)


if __name__ == "__main__":
    main()
